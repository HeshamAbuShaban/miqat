#!/usr/bin/env python3
"""Fit the EFFECTIVE method parameters from the donor corpus (staticprayertimes).

The donor's live pipeline (t5.a + y5.g + qibla seasonal layer, decoded in
docs/engine-parity.md) reproduces its own shipped fallback table only to ±2-3 min:
the corpus was generated by an earlier revision with different base parameters.
This fitter derives, per method, the parameter set that DOES reproduce the corpus
(≥99% @ ±1 min target) using the same mechanism the donor's `qibla` table uses:

  base: fajr/isha angles + per-prayer minute margins (+ maghrib mode/value)
  layer: per-window (monthly) minute corrections on the margin slots
         — donor qibla columns fm/sm/dm/am/mm/im semantics

Corrupt corpus rows (|residual| > 25 min at fitted params, e.g. rasalkhaimah
20140312 dhuhr "06:26") are excluded from fitting and reported.

Output: tools/fitted_methods.json  (11-slot params + monthly windows)
Usage:  python3 -I tools/fit_methods.py [--method NAME]
"""
import argparse
import json
import math
import sqlite3
import sys

sys.path.insert(0, "tools")
import verify_engine as ve  # solar core + city resolution + DST


def prep(rows, cities, country):
    out = []
    for (slug, date, f, sr, dh, asr, mg, isha) in rows:
        cc = ve.resolve(cities, slug.lower().replace(" ", "").replace("-", ""), country)
        if cc is None:
            continue
        lat, lon, tzh, alt = cc
        y, mo, dy = int(date[:4]), int(date[4:6]), int(date[6:8])
        try:
            want = {"fajr": ve.parse_hhmm(f), "sunrise": ve.parse_hhmm(sr),
                    "dhuhr": ve.parse_hhmm(dh), "asr": ve.parse_hhmm(asr),
                    "maghrib": ve.parse_hhmm(mg), "isha": ve.parse_hhmm(isha)}
        except ValueError:
            continue  # malformed corpus cell (e.g. "12.29", "#VALEUR!")
        jd = ve.julian(y, mo, dy) - lon / 360.0
        r = {
            "slug": slug, "y": y, "mo": mo, "dy": dy,
            "lat": lat, "lon": lon, "tzh": tzh,
            "want": want,
        }
        # donor evaluates each slot at its own initial day-fraction — cache per slot
        r["cache"] = {}
        for ci, t0 in ((0, 5 / 24), (1, 6 / 24), (2, 13 / 24), (3, 18 / 24)):
            decl, eqt = ve.sun_position(jd + t0)
            r["cache"][ci] = (decl, ve.fix(12.0 - eqt, 24.0))
        _, eqt12 = ve.sun_position(jd + 12 / 24)
        r["transit"] = ve.fix(12.0 - eqt12, 24.0)
        r["sinlat"] = math.sin(math.radians(lat))
        r["coslat"] = math.cos(math.radians(lat))
        out.append(r)
    # per-(city, year) DST detection: the corpus is hand-authored in Excel and
    # not even internally uniform within one method. For each group compare the
    # spread of sunrise residuals with vs without the DST hour — the correct
    # variant has the smaller spread (margin is constant, std is mean-free).
    groups = {}
    for r in out:
        groups.setdefault((r["slug"], r["y"]), []).append(r)
    for g in groups.values():
        r0 = g[0]
        variants = {}
        for dst in (False, True):
            res = []
            for r in g:
                sh = r["tzh"] + (ve.dst_hours(r["y"], r["mo"], r["dy"], country) if dst else 0.0) - r["lon"] / 15.0
                decl, noon = r["cache"][1]
                num = -math.sin(math.radians(180 - 0.833)) - math.sin(math.radians(decl)) * r["sinlat"]
                den = math.cos(math.radians(decl)) * r["coslat"]
                x = num / den
                if abs(x) > 1 or den == 0:
                    continue
                dt = math.degrees(math.acos(x)) / 15.0
                res.append(r["want"]["sunrise"] - ((noon - dt + sh) % 24) * 60.0)
            if len(res) >= 2:
                mu = sum(res) / len(res)
                variants[dst] = sum((x - mu) ** 2 for x in res) / len(res)
        best = min(variants, key=lambda k: variants[k]) if variants else False
        for r in g:
            r["dst"] = best
            r["shift"] = r["tzh"] + (ve.dst_hours(r["y"], r["mo"], r["dy"], country) if best else 0.0) - r["lon"] / 15.0
    return out


def ang_t(r, angle, ci):
    """Donor t5.a.f(angle, t): angle in (90,180] = morning crossing."""
    decl, noon = r["cache"][ci]
    num = -math.sin(math.radians(angle)) - math.sin(math.radians(decl)) * r["sinlat"]
    den = math.cos(math.radians(decl)) * r["coslat"]
    if den == 0:
        return None
    x = num / den
    if abs(x) > 1:
        return None
    dt = math.degrees(math.acos(x)) / 15.0
    return ((noon - dt) if angle > 90 else noon + dt) + r["shift"]


def sunrise_t(r, sr_m):
    t = ang_t(r, 180 - 0.833, 1)
    return t + sr_m / 60.0 if t is not None else None


def sunset_t(r):
    return ang_t(r, 0.833, 3)


def fit_angle_margin(rows, key, morning, ci, sr_m, mag_m_fn, lo=12.0, hi=22.0,
                     step=0.05, mlo=-60.0, mhi=60.0):
    """Grid the angle. Margin = mean residual against the PRE-margin time
    (t0), re-evaluated while the high-lat firing set settles (the gap check
    includes the margin, mirroring the pipeline). Returns (rms, angle, margin)."""
    best = None
    a = lo
    while a <= hi + 1e-9:
        m = 0.0
        t0s = []
        for _ in range(5):  # firing set <-> margin settle
            t0s, res = [], []
            for r in rows:
                raw = ang_t(r, 180 - a if morning else a, ci)
                sr_t = sunrise_t(r, sr_m)
                night = ve.fix(sr_t - sunset_t(r), 24.0) if sr_t is not None else 0.0
                if morning:
                    pf = (a / 60.0) * night
                    if raw is None or ve.fix(sr_t - (raw + m / 60.0), 24.0) > pf:
                        t0 = sr_t - pf if sr_t is not None else None
                    else:
                        t0 = raw
                else:
                    mag_t = mag_m_fn(r)
                    pi = (a / 60.0) * night
                    if raw is None or ve.fix((raw + m / 60.0) - mag_t, 24.0) > pi:
                        t0 = mag_t + pi if mag_t is not None else None
                    else:
                        t0 = raw
                t0s.append(t0)
                if t0 is not None:
                    res.append(r["want"][key] - (t0 % 24) * 60.0)
            m = sum(res) / len(res) if res else 0.0
            m = max(mlo, min(mhi, m))
        err = n = 0
        for r, t0 in zip(rows, t0s):
            if t0 is None:
                err += (100.0) ** 2
            else:
                e = r["want"][key] - ((t0 + m / 60.0) % 24) * 60.0
                err += e * e
            n += 1
        rms = math.sqrt(err / n)
        if best is None or rms < best[0]:
            best = (rms, round(a, 2), round(m, 3))
        a += step
    return best


def fit_margin(rows, key, t_fn):
    res = [r["want"][key] - (t_fn(r) % 24) * 60.0
           for r in rows if t_fn(r) is not None]
    m = sum(res) / len(res)
    rms = math.sqrt(sum((x - m) ** 2 for x in res) / len(res))
    return m, rms


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--method", type=str, default=None)
    args = ap.parse_args()

    con = sqlite3.connect("file:" + ve.DB + "?mode=ro", uri=True)
    cities = ve.load_cities(con)
    q = ("SELECT methodname, city, date, fajr, sunrise, dhuhr, asr, maghrib, isha"
         " FROM staticprayertimes")
    qargs = ()
    if args.method:
        q += " WHERE methodname = ?"
        qargs = (args.method,)
    all_rows = con.execute(q, qargs).fetchall()
    by_method = {}
    for row in all_rows:
        by_method.setdefault(row[0], []).append(row[1:])  # drop methodname col

    fitted = {}
    corrupt_all = []
    for method, rows in sorted(by_method.items()):
        country = ve.METHOD_COUNTRY.get(method)
        # DST resolved per (city, year) inside prep(); methods read it back
        data = prep(rows, cities, country)
        if not data:
            continue
        dst_used = any(r["dst"] for r in data)

        # stage 1: sunrise margin (0.833 horizon)
        sr_m, sr_rms = fit_margin(data, "sunrise", lambda r: ang_t(r, 180 - 0.833, 1))

        # stage 2: maghrib — grid angle around sunset; if it lands on ~0.833 the
        # effective mode is "minutes after sunset"
        best_mg = None
        a = 0.0
        while a <= 7.0 + 1e-9:
            res = []
            for r in data:
                t = ang_t(r, a, 3)
                if t is not None:
                    res.append(r["want"]["maghrib"] - (t % 24) * 60.0)
            if res:
                m = sum(res) / len(res)
                rms = math.sqrt(sum((x - m) ** 2 for x in res) / len(res))
                if best_mg is None or rms < best_mg[0]:
                    best_mg = (rms, round(a, 2), round(m, 3))
            a += 0.05
        mg_rms, mg_angle, mg_margin = best_mg
        mg_minutes_mode = abs(mg_angle - 0.833) < 0.15

        def mag_m_fn(r, _mg_minutes_mode=mg_minutes_mode, _mg_angle=mg_angle,
                     _mg_margin=mg_margin, _sr_m=sr_m):
            if _mg_minutes_mode:
                return sunset_t(r) + _mg_margin / 60.0
            t = ang_t(r, _mg_angle, 3)
            return t + _mg_margin / 60.0 if t is not None else None

        # stage 3: dhuhr margin
        dh_m, dh_rms = fit_margin(data, "dhuhr",
                                  lambda r: r["transit"] + r["shift"])

        # stage 4: asr margin, shafii (shadow 1) vs hanafi (shadow 2)
        asr_opts = []
        for shadow in (1.0, 2.0):
            def asr_fn(r, _s=shadow):
                decl = r["cache"][2][0]
                angle = -math.degrees(math.atan2(
                    1.0, _s + math.tan(math.radians(abs(r["lat"] - decl)))))
                return ang_t(r, angle, 2)
            asr_opts.append((fit_margin(data, "asr", asr_fn), shadow))
        best_asr = None
        for (m, rms), shadow in asr_opts:
            if best_asr is None or rms < best_asr[1] - 0.3 or (
                    abs(rms - best_asr[1]) <= 0.3 and abs(m) < abs(best_asr[0])):
                best_asr = (m, rms, shadow)
        asr_m, asr_rms, asr_shadow = best_asr

        # stages 5/6: fajr + isha (angle grid, high-lat aware)
        fj = fit_angle_margin(data, "fajr", morning=True, ci=0, sr_m=sr_m,
                              mag_m_fn=mag_m_fn)
        ish = fit_angle_margin(data, "isha", morning=False, ci=3, sr_m=sr_m,
                               mag_m_fn=mag_m_fn)
        fj_rms, fj_angle, fj_margin = fj
        is_rms, is_angle, is_margin = ish

        # base residuals per row (windows not yet applied)
        def base_resid(r):
            decl = r["cache"][2][0]
            aangle = -math.degrees(math.atan2(
                1.0, asr_shadow + math.tan(math.radians(abs(r["lat"] - decl)))))
            cand = {
                "fajr": ang_t(r, 180 - fj_angle, 0),
                "sunrise": ang_t(r, 180 - 0.833, 1),
                "dhuhr": r["transit"] + r["shift"],
                "asr": ang_t(r, aangle, 2),
                "maghrib": mag_m_fn(r),
                "isha": ang_t(r, is_angle, 3),
            }
            marg = {"fajr": fj_margin, "sunrise": sr_m, "dhuhr": dh_m,
                    "asr": asr_m, "maghrib": 0.0, "isha": is_margin}
            out = {}
            for k, t in cand.items():
                out[k] = None if t is None else r["want"][k] - ((t + marg[k] / 60.0) % 24) * 60.0
            return out

        base = [(r, base_resid(r)) for r in data]

        # half-month window corrections (donor qibla fm/sm/dm/am/mm/im semantics;
        # donor uses fine windows too — dubai windows span 5-9 days)
        def half_month(r):
            return (r["mo"], 1 if r["dy"] <= 15 else 16)

        wins = {}
        for r, res in base:
            acc = wins.setdefault(half_month(r), {k: [] for k in res})
            for k, v in res.items():
                if v is not None:
                    acc[k].append(v)
        win_mean = {}
        for hm, acc in wins.items():
            win_mean[hm] = {k: (sum(v) / len(v) if v else 0.0) for k, v in acc.items()}
        window_rows = []
        col = {"fajr": "fm", "sunrise": "sm", "dhuhr": "dm",
               "asr": "am", "maghrib": "mm", "isha": "im"}
        for hm in sorted(win_mean):
            mo, start = hm
            corr = {k: round(m, 2) for k, m in win_mean[hm].items() if abs(m) >= 0.30}
            if corr:
                window_rows.append(dict(b=mo * 100 + start,
                                        e=mo * 100 + (15 if start == 1 else 31),
                                        **{col[k]: corr.get(k, 0.0) for k in col}))

        # per-city offsets (donor `qibla` table's `c` column semantics): the corpus
        # was authored per city from different calendar sources — a method-level
        # layer cannot carry per-city base shifts. Emit offsets where a city's
        # post-window mean exceeds 1 min on any prayer.
        city_acc = {}
        for r, res in base:
            acc = city_acc.setdefault(r["slug"], {k: [] for k in res})
            wm = win_mean[half_month(r)]
            for k, v in res.items():
                if v is not None and abs(v - wm[k]) <= 25.0:
                    acc[k].append(v - wm[k])
        city_offsets = {}
        for slug, acc in sorted(city_acc.items()):
            offs = {}
            for k, vals in acc.items():
                m = sum(vals) / len(vals)
                if abs(m) > 1.0:
                    offs[col[k]] = round(m, 2)
            if offs:
                city_offsets[slug] = offs

        # corrupt rows: residual > 25 min on any prayer at (base + windows + city)
        corrupt, clean = [], []
        for r, res in base:
            co = city_offsets.get(r["slug"], {})
            full = {k: (None if v is None else v - win_mean[half_month(r)][k]
                        - co.get(col[k], 0.0))
                    for k, v in res.items()}
            bad = any(v is None or abs(v) > 25 for v in full.values())
            if bad:
                corrupt.append((r["slug"], f"{r['y']}{r['mo']:02d}{r['dy']:02d}",
                                {k: (None if v is None else round(v, 1))
                                 for k, v in full.items()
                                 if v is None or abs(v) > 25}))
            else:
                clean.append((r, full))

        # 11-slot params (same format as donor y5.g):
        # [0] fajr angle, [1] maghrib mode (1=min), [2] maghrib value,
        # [3] isha mode (0=angle), [4] isha angle, [5..10] margins
        if mg_minutes_mode:
            slots = [fj_angle, 1.0, round(mg_margin, 2), 0.0, is_angle,
                     round(fj_margin, 2), round(sr_m, 2), round(dh_m, 2),
                     round(asr_m, 2), 0.0, round(is_margin, 2)]
        else:
            slots = [fj_angle, 0.0, round(mg_angle, 2), 0.0, is_angle,
                     round(fj_margin, 2), round(sr_m, 2), round(dh_m, 2),
                     round(asr_m, 2), round(mg_margin, 2), round(is_margin, 2)]
        fitted[method] = {
            "country": country,
            "dst": dst_used,
            "params": slots,
            "asr_shadow": int(asr_shadow),
            "windows": window_rows,
            "city_offsets": city_offsets,
            "rms": {k: round(math.sqrt(sum(v * v for _, res in clean for kk, v in res.items() if kk == k) /
                                          max(1, sum(1 for _ in clean))), 3)
                    for k in ("fajr", "sunrise", "dhuhr", "asr", "maghrib", "isha")},
            "corpus_rows": len(rows), "corrupt_rows": len(corrupt),
        }
        corrupt_all += [(method, *c) for c in corrupt]
        print(f"{method:<12} fajr {fj_angle:5.2f}/{fj_margin:+5.2f}  sunrise {sr_m:+5.2f}  "
              f"dhuhr {dh_m:+5.2f}  asr sh{asr_shadow:.0f} {asr_m:+5.2f}  "
              f"maghrib {'min+' if mg_minutes_mode else ''}{mg_angle if not mg_minutes_mode else ''}"
              f"{'' if mg_minutes_mode else '°'}/{mg_margin:+5.2f}  "
              f"isha {is_angle:5.2f}/{is_margin:+5.2f}  | rms {max(fj_rms, sr_rms, dh_rms, asr_rms, mg_rms, is_rms):.2f}"
              + (f"  cityoffs={len(city_offsets)}" if city_offsets else "")
              + (f"  corrupt={len(corrupt)}" if corrupt else ""), flush=True)

    json.dump(fitted, open("tools/fitted_methods.json", "w"), indent=1, ensure_ascii=False)
    print(f"\nwrote tools/fitted_methods.json ({len(fitted)} methods)")
    if corrupt_all:
        print(f"corpus corrupt rows excluded ({len(corrupt_all)}):")
        for c in corrupt_all:
            print("  ", c)


if __name__ == "__main__":
    main()
